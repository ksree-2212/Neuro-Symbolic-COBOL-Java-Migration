import re
from typing import Dict, Any, List, Optional
from backend.app.schemas.test_result import TestResultSchema
from backend.app.schemas.ast_graph import GraphData

class FailureAnalyzer:
    """
    Diagnoses compilation and differential verification failures.
    Traces output mismatches to missing graph nodes, copybooks, or numeric precision issues.
    """
    @staticmethod
    def diagnose_compile_failure(compile_errors: str) -> Dict[str, Any]:
        category = "COMPILE_ERROR"
        diagnosis = "General compilation failure."

        if "cannot find symbol" in compile_errors:
            m = re.search(r'symbol:\s*variable\s+([A-Za-z0-9_]+)', compile_errors)
            sym = m.group(1) if m else "unknown"
            category = "MISSING_DEPENDENCY"
            diagnosis = f"Undefined symbol '{sym}'. Symbol was referenced in Java but missing from imported definitions."
        elif "incompatible types" in compile_errors:
            category = "TYPE_ERROR"
            diagnosis = "Type mismatch between variable assignment or arithmetic operator."
        elif "package" in compile_errors and "does not exist" in compile_errors:
            category = "MISSING_IMPORT"
            diagnosis = "Referenced package or class import is missing."
        elif "';' expected" in compile_errors or "illegal start of expression" in compile_errors:
            category = "SYNTAX_ERROR"
            diagnosis = "Java syntax or punctuation error generated by LLM."

        return {
            "category": category,
            "diagnosis": diagnosis,
            "root_cause": "Compilation verification rejected the generated artifact."
        }

    @staticmethod
    def diagnose_test_failures(failing_results: List[TestResultSchema], graph: Optional[GraphData] = None) -> Dict[str, Any]:
        if not failing_results:
            return {"category": "NONE", "diagnosis": "All tests passed.", "root_cause": "N/A"}

        first_failure = failing_results[0]
        diff_text = first_failure.difference or ""

        # Trace failure against graph knowledge
        category = "OUTPUT_MISMATCH"
        diagnosis = f"Behavioral divergence detected: {diff_text}"

        if "discount" in diff_text.lower():
            category = "MISSING_DEPENDENCY"
            diagnosis = (
                "Discount calculation mismatch. Original COBOL logic applies customer-specific discounts, "
                "which indicates the translation omitted the conditional branch or the copybook/discount paragraph."
            )
        elif "numeric divergence" in diff_text.lower():
            category = "NUMERIC_PRECISION"
            diagnosis = (
                "Numeric precision or rounding mismatch. COBOL fixed-point decimal arithmetic "
                "differs from Java floating point or rounding mode."
            )
        elif "runtime error" in diff_text.lower():
            category = "RUNTIME_ERROR"
            diagnosis = f"Uncaught runtime exception in generated Java code: {diff_text}"

        return {
            "category": category,
            "diagnosis": diagnosis,
            "failing_count": len(failing_results),
            "sample_difference": diff_text
        }
